"""Write Madeira's ddraw.ini for cnc-ddraw.

The base is cnc-ddraw's own ini: the text cfg_create_ini() in
third_party/cnc-ddraw/src/config.c writes when no ddraw.ini exists. It carries
the documented defaults and upstream's per-game sections (about 290 titles).
Madeira changes only what its platform requires (MADEIRA_CHANGES.md):

  [ddraw]
    renderer=direct3d9   'auto' skips Direct3D 9 under Wine (src/dd.c,
                         '!IsWine() && d3d9_is_available()') and then tries
                         OpenGL, which has no backend on iOS, ending in GDI.
                         Direct3D 9 is DXMT's, i.e. Metal.
    fullscreen=true      upscale to the guest desktop instead of changing the
    maintas=true         display mode, keeping the aspect ratio.
    singlecpu=false      process affinity does not help under FEX.
    no_compat_warning=true  no message box (a modal dialog on an iPad looks
                         like a frozen game).
  per-game sections
    renderer=opengl -> renderer=direct3d9 (OpenGL has no backend here; the
                         alternative would be GDI). renderer=gdi is kept.

    build/ddraw/make-ini.py OUT.ini            (from the default config.c)
    build/ddraw/make-ini.py OUT.ini --config path/to/config.c
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DDRAW_SECTION = {
    'renderer': 'direct3d9',
    'fullscreen': 'true',
    'maintas': 'true',
    'singlecpu': 'false',
    'no_compat_warning': 'true',
}
HEADER = ('; Madeira: generated by build/ddraw/make-ini.py from cnc-ddraw\'s own defaults\n'
          '; (third_party/cnc-ddraw/src/config.c, cfg_create_ini). Madeira\'s changes are\n'
          '; marked "; Madeira:". Delete C:\\ProgramData\\cnc-ddraw\\ddraw.ini to get a fresh copy.\n')

C_ESCAPES = {'n': '\n', 't': '\t', '\\': '\\', '"': '"', "'": "'", '0': '\0', 'r': '\r'}


def upstream_ini(config_c: Path) -> str:
    src = config_c.read_text(encoding='utf-8')
    start = src.index('static void cfg_create_ini()\n{')
    body = src[start:]
    call = body.index('fputs(')
    end = body.index(', fh);', call)
    literals = re.findall(r'"((?:[^"\\]|\\.)*)"', body[call + len('fputs('):end])
    if len(literals) < 100:
        raise SystemExit(f'make-ini: cfg_create_ini has {len(literals)} string pieces; the source changed shape')
    text = ''.join(literals)
    return re.sub(r'\\(.)', lambda m: C_ESCAPES.get(m.group(1), m.group(1)), text)


def madeira_ini(text: str) -> tuple[str, dict]:
    out, section, seen, stats = [], None, set(), {'opengl_rewritten': [], 'sections': 0}
    for line in text.split('\n'):
        m = re.match(r'^\[(.+)\]\s*$', line)
        if m:
            if section == 'ddraw':
                for key in DDRAW_SECTION:
                    if key not in seen:
                        raise SystemExit(f'make-ini: [ddraw] has no {key}= line to change')
            section = m.group(1)
            stats['sections'] += 1
            out.append(line)
            continue
        kv = re.match(r'^([A-Za-z0-9_]+)=(.*)$', line)
        if kv and section == 'ddraw' and kv.group(1) in DDRAW_SECTION:
            key = kv.group(1)
            seen.add(key)
            if kv.group(2) != DDRAW_SECTION[key]:
                out.append(f'; Madeira: was {key}={kv.group(2)}')
            out.append(f'{key}={DDRAW_SECTION[key]}')
            continue
        if kv and section != 'ddraw' and kv.group(1) == 'renderer' and kv.group(2).lower().startswith('opengl'):
            stats['opengl_rewritten'].append(section)
            out.append(f'; Madeira: was renderer={kv.group(2)} (no OpenGL on iOS)')
            out.append('renderer=direct3d9')
            continue
        out.append(line)
    return HEADER + '\n'.join(out), stats


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('out', type=Path)
    ap.add_argument('--config', type=Path, default=ROOT / 'third_party/cnc-ddraw/src/config.c')
    a = ap.parse_args()
    text, stats = madeira_ini(upstream_ini(a.config))
    a.out.write_text(text.replace('\n', '\r\n'), encoding='utf-8', newline='')  # the bytes cfg_create_ini would write
    print(f'make-ini: wrote {a.out}: {stats["sections"]} sections, '
          f'renderer=opengl -> direct3d9 in {len(stats["opengl_rewritten"])} game sections')
    return 0


if __name__ == '__main__':
    sys.exit(main())
